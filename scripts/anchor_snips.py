"""Capture the HSR screen in three states and crop every anchor for review.

Dev tool only (requires Pillow, which is not a runtime dependency). It writes
docs/anchors/hsr/<state>/<anchor>.png plus an index README so a human can eyeball
what each anchor points at after a calibration session.

    python scripts/anchor_snips.py
"""

from __future__ import annotations

import json
import pathlib
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from kiseki_runtime.tools import Runtime  # noqa: E402

OUT = ROOT / "docs" / "anchors" / "hsr"
GAME = "hsr"


def state_of(anchor_id: str) -> str:
    if anchor_id == "title_enter":
        return "title"
    if anchor_id.startswith("phone_"):
        return "phone"
    if anchor_id.startswith("map_"):
        return "map"
    return "ingame"


def main() -> int:
    try:
        from PIL import Image
    except ImportError:
        print("Pillow is required for this dev tool: pip install pillow")
        return 1

    runtime = Runtime()
    profile = runtime.profile(GAME)
    anchors = profile.get("ui", {}).get("anchors", [])
    runtime.game_focus(GAME)

    screens: dict[str, pathlib.Path] = {}

    def grab(state: str) -> None:
        shot = runtime.game_capture(GAME, label=f"anchors-{state}")
        screens[state] = ROOT / shot["relative_path"]

    # in-game
    for _ in range(3):
        runtime.game_skill(GAME, "close_panel", dry_run=False)
        time.sleep(0.6)
    grab("ingame")
    # phone
    runtime.game_skill(GAME, "phone_open", dry_run=False)
    time.sleep(2.0)
    grab("phone")
    runtime.game_skill(GAME, "phone_close", dry_run=False)
    time.sleep(1.5)
    # map
    runtime.game_act(GAME, [{"type": "key", "keys": ["m"], "action": "tap"}], dry_run=False)
    time.sleep(2.5)
    grab("map")
    runtime.game_skill(GAME, "close_panel", dry_run=False)
    time.sleep(1.0)

    index_rows = []
    skipped = [anchor.get("id", "") for anchor in anchors if state_of(anchor.get("id", "")) not in screens]
    for state, path in screens.items():
        image = Image.open(path)
        width, height = image.size
        folder = OUT / state
        folder.mkdir(parents=True, exist_ok=True)
        for anchor in anchors:
            anchor_id = anchor.get("id", "")
            if state_of(anchor_id) != state:
                continue
            x0, y0, x1, y1 = anchor["region"]
            box = (int(x0 * width), int(y0 * height), int(x1 * width), int(y1 * height))
            crop = image.crop(box)
            crop.save(folder / f"{anchor_id}.png")
            index_rows.append(
                {
                    "state": state,
                    "id": anchor_id,
                    "region": anchor["region"],
                    "size": list(crop.size),
                    "note": anchor.get("note", ""),
                }
            )

    lines = [
        "# HSR anchor evidence",
        "",
        "Generated by `scripts/anchor_snips.py` on the real client (2560x1600, DPI 120%).",
        "Each PNG is the exact crop the anchor maps to; regenerate after changing regions.",
        "",
        "| state | anchor | region | size | note |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in index_rows:
        note = str(row["note"]).replace("|", "/")
        lines.append(
            f"| {row['state']} | `{row['id']}` | {row['region']} | {row['size'][0]}x{row['size'][1]} | {note} |"
        )
    if skipped:
        lines += ["", "Not captured in these states: " + ", ".join(f"`{name}`" for name in skipped)]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"screens": {k: str(v) for k, v in screens.items()}, "anchors": len(index_rows)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
